export function foodName(name: string, locale: string): string {
  if (locale !== "fr" || !name) return name;
  const key = name.trim().toLowerCase();
  return FR[key] ?? (key.endsWith("s") ? FR[key.slice(0, -1)] : undefined) ?? name;
}

/** In a client component under app/[lang]: names shown in the page's language. */
export function useFoodName(): (name: string) => string {
  const { lang } = useParams<{ lang: string }>();
  return (name) => foodName(name, lang);
}
